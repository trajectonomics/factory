import { describe, expect, it } from "bun:test"
import { readDispatchLedger } from "./dispatch-ledger"
import type { GitHubCommentData, GitHubIssueData, GitHubPullRequestData } from "./github/client"
import { testClient } from "./github/fixtures/test-client"
import type { T3Client, T3Thread } from "./t3"

const CLI = "trajectonomics/cli"
const NOW_MS = Date.parse("2026-11-09T15:00:00Z")
const NO_THREADS: T3Client = { listThreads: async () => [], launchThread: unusedLaunch }

async function unusedLaunch(): Promise<never> {
	throw new Error("unexpected launch")
}

function pullRequest(number: number, ref: string, draft = false): GitHubPullRequestData {
	return { number, draft, created_at: "2026-11-09T10:00:00Z", head: { ref } }
}

function issue(number: number, labels: string[], body = ""): GitHubIssueData {
	return {
		number,
		state: "open",
		labels: labels.map((name) => ({ name })),
		repository_url: `https://api.github.com/repos/${CLI}`,
		body,
		created_at: "2026-11-09T09:00:00Z",
	}
}

function question(createdAt: string, association = "OWNER"): GitHubCommentData {
	return {
		id: createdAt,
		body: "This was generated by AI.\n\nWhich host?\n\n<!-- factory:comment:exit:spec-gap:which-host:ab12 -->",
		author_association: association,
		created_at: createdAt,
	}
}

function ledgerOf(
	data: {
		pulls?: GitHubPullRequestData[]
		issues?: GitHubIssueData[]
		comments?: GitHubCommentData[]
	},
	t3: T3Client = NO_THREADS,
) {
	const client = testClient({
		listPullRequests: async () => data.pulls ?? [],
		listIssues: async () => data.issues ?? [],
		listComments: async () => data.comments ?? [],
	})
	return readDispatchLedger(client, t3, [CLI], NOW_MS)
}

describe("reading the Dispatcher ledger", () => {
	it("lists open Factory pull requests with the issue their branch names", async () => {
		const ledger = await ledgerOf({
			pulls: [pullRequest(8, "factory/4-add-thing"), pullRequest(9, "feat/other")],
		})

		expect(ledger.pullRequests).toEqual([
			{
				issue: { repository: CLI, number: 4 },
				number: 8,
				head: "factory/4-add-thing",
				draft: false,
				openedAtMs: Date.parse("2026-11-09T10:00:00Z"),
			},
		])
	})

	it("reports a draft Factory pull request as a gate-failure Exit", async () => {
		const ledger = await ledgerOf({ pulls: [pullRequest(8, "factory/spec-4-a-spec", true)] })

		expect(ledger.exits).toEqual([
			{
				issue: { repository: CLI, number: 4 },
				kind: "gate-failure",
				atMs: Date.parse("2026-11-09T10:00:00Z"),
			},
		])
	})

	it("reports a needs-info issue with a Factory question as a spec-gap Exit at the latest question", async () => {
		const ledger = await ledgerOf({
			issues: [issue(5, ["needs-info"])],
			comments: [question("2026-11-09T11:00:00Z"), question("2026-11-09T12:00:00Z")],
		})

		expect(ledger.exits).toEqual([
			{
				issue: { repository: CLI, number: 5 },
				kind: "spec-gap",
				atMs: Date.parse("2026-11-09T12:00:00Z"),
			},
		])
	})

	it("ignores a needs-info issue whose only question marker comes from a stranger", async () => {
		const ledger = await ledgerOf({
			issues: [issue(5, ["needs-info"])],
			comments: [question("2026-11-09T11:00:00Z", "NONE")],
		})

		expect(ledger.exits).toEqual([])
	})

	it("ignores a needs-info issue that carries no Factory question", async () => {
		const ledger = await ledgerOf({ issues: [issue(5, ["needs-info"])], comments: [] })

		expect(ledger.exits).toEqual([])
	})

	it("reports an open ready-for-human issue that names its origin as a follow-up Exit", async () => {
		const ledger = await ledgerOf({
			issues: [
				issue(6, ["ready-for-human"], "Follow-up from #4.\n\nCreate the token."),
				issue(7, ["ready-for-human"], "Collect the documents."),
			],
		})

		expect(ledger.exits).toEqual([
			{
				issue: { repository: CLI, number: 4 },
				kind: "follow-up",
				atMs: Date.parse("2026-11-09T09:00:00Z"),
			},
		])
	})

	it("reports a waiting Run thread as an urgent Exit dated by the pass", async () => {
		const thread = (title: string, status: T3Thread["status"]): T3Thread => ({
			id: title,
			title,
			status,
		})
		const t3: T3Client = {
			listThreads: async () => [
				thread(`traj/${CLI}#4`, "waiting"),
				thread(`traj/${CLI}#5`, "running"),
				thread(`triage/${CLI}#6`, "waiting"),
			],
			launchThread: unusedLaunch,
		}

		const ledger = await ledgerOf({}, t3)

		expect(ledger.exits).toEqual([
			{ issue: { repository: CLI, number: 4 }, kind: "urgent", atMs: NOW_MS },
		])
	})
})
