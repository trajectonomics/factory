import type { IssueKey } from "../contracts"
import { deepFreeze } from "../freeze"
import { copyIssueKey } from "../keys"
import type { BoardStatus } from "./board"
import { assertClaimTime } from "./claim-time"
import { GitHubAdapterError } from "./errors"
import type { FollowUpWrite, PullRequestWrite } from "./run-writes"

/** The first line of every comment the Factory posts. */
export const AI_DISCLAIMER: string = "This was generated by AI."

const COMMENT_KEY_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._:-]*$/

/** Adds the `agent-working` Claim label; its label event supplies `claimedAtMs` on read. */
export type ClaimWrite = {
	readonly kind: "claim"
	readonly issue: IssueKey
	readonly claimedAtMs: number
}

/** Adds or removes one label. */
export type LabelWrite = {
	readonly kind: "label"
	readonly issue: IssueKey
	readonly label: string
	readonly present: boolean
}

/** Moves one card to a board Status. */
export type StatusWrite = {
	readonly kind: "status"
	readonly issue: IssueKey
	readonly status: BoardStatus
}

/** Posts one comment, idempotent by its stable key. */
export type CommentWrite = {
	readonly kind: "comment"
	readonly issue: IssueKey
	readonly key: string
	readonly body: string
}

export type { FollowUpWrite, PullRequestWrite } from "./run-writes"
export { followUpWrite, pullRequestWrite } from "./run-writes"

/** One write the Factory asks GitHub to perform. */
export type FactoryWrite =
	| ClaimWrite
	| LabelWrite
	| StatusWrite
	| CommentWrite
	| PullRequestWrite
	| FollowUpWrite

/** Creates a Claim write for an issue. */
export function claimWrite(issue: IssueKey, claimedAtMs: number): ClaimWrite {
	assertClaimTime(claimedAtMs, "writes[claim].claimedAtMs")
	return deepFreeze({ kind: "claim", issue: copyIssueKey(issue), claimedAtMs })
}

/** Creates a label write that either adds or removes the label. */
export function labelWrite(issue: IssueKey, label: string, present: boolean): LabelWrite {
	return deepFreeze({ kind: "label", issue: copyIssueKey(issue), label, present })
}

/** Creates a board Status write. */
export function statusWrite(issue: IssueKey, status: BoardStatus): StatusWrite {
	return deepFreeze({ kind: "status", issue: copyIssueKey(issue), status })
}

/** Creates a comment write with the AI disclaimer and a stable idempotency marker. */
export function commentWrite(issue: IssueKey, key: string, body: string): CommentWrite {
	assertCommentKey(key, "writes[comment].key")
	const text = body.trim()
	const disclosed = text.startsWith(AI_DISCLAIMER) ? text : `${AI_DISCLAIMER}\n\n${text}`
	const marked = disclosed.includes(commentMarker(key))
		? disclosed
		: `${disclosed}\n\n${commentMarker(key)}`
	return deepFreeze({ kind: "comment", issue: copyIssueKey(issue), key, body: marked })
}

/** The hidden marker that makes a comment idempotent on re-run. */
export function commentMarker(key: string): string {
	return `<!-- factory:comment:${key} -->`
}

/** Rejects a comment key that cannot be embedded in its marker. */
export function assertCommentKey(key: string, field: string): void {
	if (COMMENT_KEY_PATTERN.test(key)) return
	throw new GitHubAdapterError(
		"invalid-comment-key",
		field,
		`A comment key must be letters, digits, dot, colon, underscore or dash: ${key}`,
	)
}

/** Whether an existing comment is one the Factory already posted for this key. */
export function isFactoryComment(body: string, key: string): boolean {
	return body.startsWith(AI_DISCLAIMER) && body.includes(commentMarker(key))
}
